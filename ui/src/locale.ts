export const panelText = { en, 'zh-CN': zh };
export type Language = keyof typeof panelText;

const thinkingKeys = ['inherit', 'off', 'none', 'minimal', 'low', 'medium', 'high', 'xhigh', 'max', 'ultra'] as const;
type Thinking = typeof thinkingKeys[number];

export function thinkingLabel(language: Language, level: string): string {
  return thinkingKeys.includes(level as Thinking) ? panelText[language][level as Thinking] : level;
}
